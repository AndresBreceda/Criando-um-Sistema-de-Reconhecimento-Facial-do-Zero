def run_webcam_recognition(model):
    cap = cv2.VideoCapture(0)
    if not cap.isOpened():
        print("No se puede abrir webcam")
        return
    while True:
        ret, frame = cap.read()
        if not ret:
            break
        out = recognize_faces_in_image(frame, model, threshold=0.6)
        cv2.imshow("Reconocimiento facial", out)
        if cv2.waitKey(1) & 0xFF == ord('q'):
            break
    cap.release()
    cv2.destroyAllWindows()

